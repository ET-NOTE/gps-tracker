CREATE TABLE rental_fleet_work (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id bigint NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    contract_id bigint REFERENCES rental_contracts(id) ON DELETE SET NULL,
    kind text NOT NULL CHECK (kind IN ('cleaning','inspection','maintenance','accident','breakdown')),
    starts_at timestamptz NOT NULL,
    ends_at timestamptz,
    note text NOT NULL CHECK (char_length(note) <= 1000),
    closed_at timestamptz,
    resolution text CHECK (char_length(resolution) <= 800),
    inspection_released_at timestamptz,
    return_inspection boolean NOT NULL DEFAULT false,
    CHECK ((kind IN ('accident','breakdown') AND ends_at IS NULL AND length(trim(note)) > 0)
        OR (kind IN ('cleaning','inspection','maintenance') AND ends_at > starts_at AND ends_at IS NOT NULL)
        OR (return_inspection AND kind='inspection' AND ends_at IS NULL)),
    CHECK (NOT return_inspection OR (kind='inspection' AND ends_at IS NULL)),
    CHECK (inspection_released_at IS NULL OR (closed_at IS NOT NULL AND kind IN ('accident','breakdown'))),
    CHECK ((closed_at IS NULL AND resolution IS NULL) OR closed_at IS NOT NULL)
);
CREATE INDEX rental_fleet_work_owner_date ON rental_fleet_work(owner_id, starts_at DESC);
CREATE INDEX rental_fleet_work_vehicle ON rental_fleet_work(owner_id, device_id, starts_at);
CREATE UNIQUE INDEX rental_return_inspection_contract ON rental_fleet_work(owner_id,contract_id) WHERE return_inspection;

CREATE TABLE rental_vehicle_profile (
    owner_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id bigint NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    branch text NOT NULL DEFAULT '' CHECK (char_length(branch)<=80),
    class_name text NOT NULL DEFAULT '' CHECK (char_length(class_name)<=80),
    readiness text NOT NULL DEFAULT 'ready' CHECK (readiness IN ('ready','hold')),
    odometer_km integer CHECK (odometer_km>=0),
    fuel_level integer CHECK (fuel_level BETWEEN 0 AND 100),
    revision bigint NOT NULL DEFAULT 1,
    PRIMARY KEY(owner_id,device_id)
);
