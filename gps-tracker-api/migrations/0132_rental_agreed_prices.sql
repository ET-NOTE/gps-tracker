-- Existing contracts use the original duration-based calculation. Only explicit new
-- agreements receive fixed prices, separately recorded extensions and manual settlement.
-- Legacy records retain their original settlement-based housekeeping schedule.
-- An unpaid fixed-price return has a physical return timestamp even before settlement.
CREATE FUNCTION rental_retention_anchor(terms jsonb, returned timestamptz, settled timestamptz)
RETURNS timestamptz LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN terms->'pricing'->>'mode'='agreed' THEN COALESCE(returned,settled) ELSE settled END
$$;

CREATE FUNCTION rental_agreed_money(v jsonb) RETURNS boolean LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT jsonb_typeof(v)='number' AND v::text ~ '^[0-9]{1,10}$' AND v <= to_jsonb(1000000000::bigint)
$$;
ALTER TABLE rental_contracts ADD CONSTRAINT rental_agreed_price_fields CHECK (
    COALESCE(rental_terms->'pricing'->>'mode','')<>'agreed' OR COALESCE(
        rental_agreed_money(rental_terms->'pricing'->'base_krw') AND
        rental_agreed_money(rental_terms->'pricing'->'option_krw') AND
        rental_agreed_money(rental_terms->'pricing'->'discount_krw') AND
        rental_agreed_money(rental_terms->'pricing'->'extension_krw') AND
        rental_agreed_money(rental_terms->'pricing'->'return_extra_krw') AND
        (rental_terms->'pricing'->>'discount_krw')::numeric <=
            (rental_terms->'pricing'->>'base_krw')::numeric + (rental_terms->'pricing'->>'option_krw')::numeric,false));
ALTER TABLE rental_contracts ADD COLUMN settlement_request_key uuid;
CREATE UNIQUE INDEX rental_settlement_request ON rental_contracts(user_id,settlement_request_key)
    WHERE settlement_request_key IS NOT NULL;

CREATE TABLE rental_agreement_extensions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id bigint NOT NULL REFERENCES rental_contracts(id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    ends_before timestamptz NOT NULL,
    ends_after timestamptz NOT NULL CHECK (ends_after>ends_before),
    additional_krw bigint NOT NULL CHECK (additional_krw BETWEEN 0 AND 1000000000),
    reason text NOT NULL DEFAULT '' CHECK (char_length(reason)<=500),
    request_key uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(owner_id,request_key)
);
CREATE INDEX rental_agreement_extension_contract ON rental_agreement_extensions(contract_id,id);

-- A pricing-only edit is not one of the legacy columns watched by migration 130.
CREATE FUNCTION rental_capture_agreed_price_edit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at)
        SELECT NEW.id,'updated',statement_timestamp()
        WHERE NOT EXISTS (SELECT FROM rental_contract_events WHERE contract_id=NEW.id
            AND event_kind='updated' AND occurred_at=statement_timestamp());
    RETURN NEW;
END $$;
CREATE TRIGGER rental_price_edit_event AFTER UPDATE OF rental_terms ON rental_contracts
    FOR EACH ROW WHEN (OLD.rental_terms->'pricing'->>'mode'='agreed' AND
        (OLD.rental_terms->'pricing'->'base_krw', OLD.rental_terms->'pricing'->'option_krw', OLD.rental_terms->'pricing'->'discount_krw')
        IS DISTINCT FROM
        (NEW.rental_terms->'pricing'->'base_krw', NEW.rental_terms->'pricing'->'option_krw', NEW.rental_terms->'pricing'->'discount_krw'))
    EXECUTE FUNCTION rental_capture_agreed_price_edit();

CREATE OR REPLACE FUNCTION rental_office_contract_fee(c rental_contracts) RETURNS numeric
LANGUAGE sql STABLE AS $$
    SELECT CASE
        WHEN c.status='cancelled' THEN CASE WHEN c.cancellation_request_key IS NULL THEN 0
            ELSE (c.rental_terms->>'cancellation_fee_krw')::bigint END
        WHEN c.rental_terms->'pricing'->>'mode'='agreed' THEN
            (c.rental_terms->'pricing'->>'base_krw')::bigint
            + (c.rental_terms->'pricing'->>'option_krw')::bigint
            - (c.rental_terms->'pricing'->>'discount_krw')::bigint
            + (c.rental_terms->'pricing'->>'extension_krw')::bigint
            + (c.rental_terms->'pricing'->>'return_extra_krw')::bigint
        ELSE rental_office_fee(c.status,c.settled_amount_krw,c.starts_at,c.ends_at,c.rate_type,c.rate_amount_krw)
    END
$$;
