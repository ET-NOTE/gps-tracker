-- A rental vehicle survives GPS replacement. Existing GPS-based clients can
-- still address their previously paired vehicles by device_id.
LOCK TABLE rental_vehicle_profile, rental_contracts, rental_fleet_work, rental_office_costs IN SHARE ROW EXCLUSIVE MODE;
ALTER TABLE rental_vehicle_profile
    DROP CONSTRAINT rental_vehicle_profile_pkey,
    DROP CONSTRAINT rental_vehicle_profile_device_id_fkey,
    ALTER COLUMN device_id DROP NOT NULL,
    ADD COLUMN vehicle_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADD COLUMN plate text NOT NULL DEFAULT '' CHECK(length(plate)<=40),
    ADD COLUMN model text NOT NULL DEFAULT '' CHECK(length(model)<=100),
    ADD COLUMN display_name text NOT NULL DEFAULT '' CHECK(length(display_name)<=100),
    ADD COLUMN identity_explicit boolean NOT NULL DEFAULT false,
    ADD UNIQUE(owner_id,vehicle_id), ADD UNIQUE(owner_id,device_id),
    ADD FOREIGN KEY(device_id) REFERENCES devices(id) ON DELETE SET NULL;
-- Include past rentals and servicing performed before the profile feature existed.
INSERT INTO rental_vehicle_profile(owner_id,device_id,revision)
    SELECT owner_id,device_id,0 FROM (
        SELECT user_id AS owner_id,device_id FROM rental_contracts UNION
        SELECT owner_id,device_id FROM rental_fleet_work UNION
        SELECT user_id,device_id FROM rental_office_costs UNION
        SELECT d.owner_id,d.id FROM devices d JOIN users u ON u.id=d.owner_id WHERE gps_owner_service(u,'rentcar')
    ) existing WHERE device_id IS NOT NULL ON CONFLICT(owner_id,device_id) DO NOTHING;
UPDATE rental_vehicle_profile p SET plate=COALESCE(left(d.license_plate,40),''),
    model=COALESCE(left(d.car_model,100),''),display_name=COALESCE(left(d.display_name,100),'')
FROM devices d WHERE p.owner_id=d.owner_id AND p.device_id=d.id;

ALTER TABLE rental_contracts DISABLE TRIGGER rental_contract_event;
ALTER TABLE rental_contracts DROP CONSTRAINT rental_unassigned_reservation,
    DROP CONSTRAINT rental_contracts_device_id_fkey,
    ADD FOREIGN KEY(device_id) REFERENCES devices(id) ON DELETE SET NULL,
    ADD COLUMN vehicle_id bigint,
    ADD FOREIGN KEY(user_id,vehicle_id) REFERENCES rental_vehicle_profile(owner_id,vehicle_id) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED;
UPDATE rental_contracts c SET vehicle_id=p.vehicle_id FROM rental_vehicle_profile p
    WHERE p.owner_id=c.user_id AND p.device_id=c.device_id;
SET CONSTRAINTS ALL IMMEDIATE;
ALTER TABLE rental_contracts ADD CONSTRAINT rental_unassigned_reservation CHECK
    (vehicle_id IS NOT NULL OR device_id IS NOT NULL OR (rental_terms IS NOT NULL AND status IN('draft','cancelled')));
CREATE INDEX rental_contract_vehicle_dates ON rental_contracts(user_id,vehicle_id,starts_at,ends_at);

ALTER TABLE rental_fleet_work DROP CONSTRAINT rental_fleet_work_device_id_fkey,
    ALTER COLUMN device_id DROP NOT NULL,
    ADD FOREIGN KEY(device_id) REFERENCES devices(id) ON DELETE SET NULL,
    ADD COLUMN vehicle_id bigint,
    ADD FOREIGN KEY(owner_id,vehicle_id) REFERENCES rental_vehicle_profile(owner_id,vehicle_id) DEFERRABLE INITIALLY DEFERRED;
UPDATE rental_fleet_work w SET vehicle_id=p.vehicle_id FROM rental_vehicle_profile p WHERE w.owner_id=p.owner_id AND w.device_id=p.device_id;
SET CONSTRAINTS ALL IMMEDIATE;
ALTER TABLE rental_fleet_work ALTER COLUMN vehicle_id SET NOT NULL;
CREATE INDEX rental_work_vehicle_dates ON rental_fleet_work(owner_id,vehicle_id,starts_at);
ALTER TABLE rental_office_costs ADD COLUMN vehicle_id bigint,
    ADD FOREIGN KEY(user_id,vehicle_id) REFERENCES rental_vehicle_profile(owner_id,vehicle_id) DEFERRABLE INITIALLY DEFERRED;
UPDATE rental_office_costs c SET vehicle_id=p.vehicle_id FROM rental_vehicle_profile p WHERE c.user_id=p.owner_id AND c.device_id=p.device_id;

-- Remember previously imported terminals so disconnecting a device never creates another vehicle.
CREATE TABLE rental_imported_devices (
    owner_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id bigint NOT NULL REFERENCES devices(id) ON DELETE CASCADE, PRIMARY KEY(owner_id,device_id)
);
INSERT INTO rental_imported_devices SELECT owner_id,device_id FROM rental_vehicle_profile WHERE device_id IS NOT NULL;
UPDATE rental_vehicle_profile p SET device_id=NULL FROM devices d WHERE d.id=p.device_id AND d.owner_id IS DISTINCT FROM p.owner_id;
UPDATE rental_contracts c SET device_id=NULL FROM devices d WHERE d.id=c.device_id AND d.owner_id IS DISTINCT FROM c.user_id;
CREATE UNIQUE INDEX rental_current_device_binding ON rental_vehicle_profile(device_id) WHERE device_id IS NOT NULL;
CREATE FUNCTION rental_import_new_devices(uid bigint) RETURNS void LANGUAGE sql AS $$
    WITH fresh AS (
        INSERT INTO rental_imported_devices(owner_id,device_id)
        SELECT owner_id,id FROM devices WHERE owner_id=uid ORDER BY id
        ON CONFLICT DO NOTHING RETURNING device_id
    )
    INSERT INTO rental_vehicle_profile(owner_id,device_id,revision,plate,model,display_name)
    SELECT uid,d.id,0,left(COALESCE(d.license_plate,''),40),left(COALESCE(d.car_model,''),100),left(COALESCE(d.display_name,''),100)
    FROM fresh JOIN devices d ON d.id=fresh.device_id AND d.owner_id=uid ON CONFLICT (owner_id,device_id) DO NOTHING
$$;
CREATE VIEW rental_asset_directory AS
SELECT p.owner_id,p.vehicle_id,p.device_id,
    CASE WHEN p.identity_explicit THEN p.plate ELSE coalesce(nullif(d.license_plate,''),p.plate) END AS plate,
    CASE WHEN p.identity_explicit THEN p.model ELSE coalesce(nullif(d.car_model,''),p.model) END AS model,
    CASE WHEN p.identity_explicit THEN p.display_name ELSE coalesce(nullif(d.display_name,''),p.display_name) END AS display_name,
    p.class_name,p.branch,p.odometer_km,p.fuel_level,p.revision,p.readiness,coalesce(d.enabled,true) AS enabled
FROM rental_vehicle_profile p LEFT JOIN devices d ON d.id=p.device_id AND d.owner_id=p.owner_id;

CREATE FUNCTION rental_detach_transferred_device() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE rental_handoff_tokens t SET revoked_at=now() FROM rental_contracts c
        WHERE c.id=t.contract_id AND c.user_id=OLD.owner_id AND c.device_id=OLD.id
          AND t.used_at IS NULL AND t.revoked_at IS NULL;
    UPDATE rental_vehicle_profile SET device_id=NULL,revision=revision+1,
        plate=CASE WHEN identity_explicit THEN plate ELSE coalesce(left(OLD.license_plate,40),plate) END,
        model=CASE WHEN identity_explicit THEN model ELSE coalesce(left(OLD.car_model,100),model) END,
        display_name=CASE WHEN identity_explicit THEN display_name ELSE coalesce(left(OLD.display_name,100),display_name) END
        WHERE device_id=OLD.id AND owner_id=OLD.owner_id;
    UPDATE rental_contracts SET device_id=NULL WHERE device_id=OLD.id AND user_id=OLD.owner_id;
    DELETE FROM rental_imported_devices WHERE device_id=OLD.id AND owner_id=NEW.owner_id;
    RETURN NEW;
END $$;
CREATE TRIGGER rental_device_owner_change AFTER UPDATE OF owner_id ON devices
    FOR EACH ROW WHEN(OLD.owner_id IS DISTINCT FROM NEW.owner_id) EXECUTE FUNCTION rental_detach_transferred_device();

-- Keep device-addressed imports and older service binaries working across a rolling deployment.
CREATE FUNCTION rental_legacy_assignment() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE uid bigint; asset bigint;
BEGIN
    uid := CASE WHEN TG_TABLE_NAME='rental_fleet_work' THEN (to_jsonb(NEW)->>'owner_id')::bigint ELSE (to_jsonb(NEW)->>'user_id')::bigint END;
    IF NEW.device_id IS NOT NULL AND (NEW.vehicle_id IS NULL OR
       (TG_OP='UPDATE' AND NEW.device_id IS DISTINCT FROM OLD.device_id AND NEW.vehicle_id IS NOT DISTINCT FROM OLD.vehicle_id)) THEN
        PERFORM rental_import_new_devices(uid);
        SELECT vehicle_id INTO STRICT asset FROM rental_vehicle_profile WHERE owner_id=uid AND device_id=NEW.device_id;
        NEW.vehicle_id := asset;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER rental_contract_vehicle BEFORE INSERT OR UPDATE OF device_id,vehicle_id ON rental_contracts
    FOR EACH ROW EXECUTE FUNCTION rental_legacy_assignment();
CREATE TRIGGER rental_work_vehicle BEFORE INSERT OR UPDATE OF device_id,vehicle_id ON rental_fleet_work
    FOR EACH ROW EXECUTE FUNCTION rental_legacy_assignment();
CREATE TRIGGER rental_cost_vehicle BEFORE INSERT OR UPDATE OF device_id,vehicle_id ON rental_office_costs
    FOR EACH ROW EXECUTE FUNCTION rental_legacy_assignment();

CREATE OR REPLACE FUNCTION rental_capture_contract_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    kinds text[] := ARRAY[]::text[];
    k text;
    stamp timestamptz := statement_timestamp();
    old_terms jsonb;
    new_terms jsonb := COALESCE(NEW.rental_terms,'{}');
    schedule_change boolean;
    other_change boolean;
BEGIN
    IF TG_OP='INSERT' THEN
        INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,source_key)
            VALUES(NEW.id,'created',NEW.created_at,'contract:created');
        IF NEW.vehicle_id IS NOT NULL THEN
            INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at)
                VALUES(NEW.id,'assigned',NEW.created_at);
        END IF;
        IF NEW.status<>'draft' THEN
            INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at)
                VALUES(NEW.id,CASE WHEN NEW.status='active' THEN 'activated' ELSE NEW.status END,NEW.created_at);
        END IF;
        RETURN NEW;
    END IF;

    old_terms := COALESCE(OLD.rental_terms,'{}');
    IF NEW.vehicle_id IS DISTINCT FROM OLD.vehicle_id THEN
        kinds := array_append(kinds, CASE WHEN NEW.vehicle_id IS NULL THEN 'unassigned' ELSE 'assigned' END);
    END IF;
    schedule_change := (NEW.starts_at,NEW.ends_at) IS DISTINCT FROM (OLD.starts_at,OLD.ends_at);
    -- Only an actual contract edit may produce a generic "updated" entry. Privacy
    -- retention and post-handoff audit notes also touch some columns via other paths.
    IF current_setting('seriallink.rental_contract_edit', true)='on' THEN
        other_change := (NEW.renter_name,NEW.renter_phone,NEW.renter_id_last4,NEW.rate_type,NEW.rate_amount_krw,
            NEW.deposit_krw,NEW.included_km_per_day,NEW.over_km_price_krw,NEW.pickup_odometer_km,
            NEW.pickup_location,NEW.return_location,NEW.note,new_terms->>'customer_id',new_terms->>'driver_id',
            new_terms->>'driver_name',new_terms->>'requested_model',new_terms->>'channel')
            IS DISTINCT FROM
            (OLD.renter_name,OLD.renter_phone,OLD.renter_id_last4,OLD.rate_type,OLD.rate_amount_krw,
            OLD.deposit_krw,OLD.included_km_per_day,OLD.over_km_price_krw,OLD.pickup_odometer_km,
            OLD.pickup_location,OLD.return_location,OLD.note,old_terms->>'customer_id',old_terms->>'driver_id',
            old_terms->>'driver_name',old_terms->>'requested_model',old_terms->>'channel');
        IF NEW.ends_at > OLD.ends_at AND OLD.starts_at=NEW.starts_at THEN
            kinds := array_append(kinds,'extended');
        ELSIF schedule_change THEN
            other_change := true;
        END IF;
        IF other_change THEN kinds := array_append(kinds,'updated'); END IF;
    END IF;
    IF COALESCE(new_terms->>'license_checked'='true',false) <> COALESCE(old_terms->>'license_checked'='true',false) THEN
        kinds := array_append(kinds, CASE WHEN new_terms->>'license_checked'='true' THEN 'license_checked' ELSE 'license_revoked' END);
    END IF;
    IF new_terms->>'confirmed_at' IS DISTINCT FROM old_terms->>'confirmed_at' THEN
        kinds := array_append(kinds, CASE WHEN new_terms->>'confirmed_at' IS NULL THEN 'review_revoked' ELSE 'reviewed' END);
    END IF;
    IF (new_terms->>'checkout_at' IS NOT NULL AND old_terms->>'checkout_at' IS NULL)
       OR (NEW.pickup_signed_at IS NOT NULL AND OLD.pickup_signed_at IS NULL AND old_terms->>'checkout_at' IS NULL) THEN
        kinds := array_append(kinds,'checkout');
    ELSIF NEW.status='active' AND OLD.status='draft' THEN
        kinds := array_append(kinds,'activated');
    END IF;
    IF NEW.status='cancelled' AND OLD.status<>'cancelled' THEN
        UPDATE rental_handoff_tokens SET revoked_at=stamp
            WHERE contract_id=NEW.id AND user_id=NEW.user_id AND used_at IS NULL AND revoked_at IS NULL;
    END IF;
    IF NEW.status IS DISTINCT FROM OLD.status AND NEW.status IN ('cancelled','overdue','returned') THEN
        kinds := array_append(kinds,CASE WHEN NEW.status='cancelled' AND NEW.cancellation_request_key IS NOT NULL
            AND new_terms->>'cancel_outcome'='no_show' THEN 'no_show' ELSE NEW.status END);
    END IF;
    IF NEW.settled_at IS NOT NULL AND OLD.settled_at IS NULL THEN kinds := array_append(kinds,'settled'); END IF;

    FOREACH k IN ARRAY kinds LOOP
        INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,starts_before,starts_after,ends_before,ends_after)
            VALUES(NEW.id,k,stamp,CASE WHEN schedule_change AND k IN ('extended','updated') THEN OLD.starts_at END,
                CASE WHEN schedule_change AND k IN ('extended','updated') THEN NEW.starts_at END,
                CASE WHEN schedule_change AND k IN ('extended','updated') THEN OLD.ends_at END,
                CASE WHEN schedule_change AND k IN ('extended','updated') THEN NEW.ends_at END);
    END LOOP;
    RETURN NEW;
END $$;
ALTER TABLE rental_contracts ENABLE TRIGGER rental_contract_event;
