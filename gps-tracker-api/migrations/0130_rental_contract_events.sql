-- A contract timeline stores event types and schedule timestamps, never customer snapshots.
-- Hold source writes while taking the baseline and installing its change capture.
LOCK TABLE rental_contracts, rental_office_ledger, rental_fleet_work IN SHARE ROW EXCLUSIVE MODE;

ALTER TABLE rental_contracts ADD COLUMN cancellation_request_key uuid;
CREATE UNIQUE INDEX rental_cancel_request ON rental_contracts(user_id,cancellation_request_key)
    WHERE cancellation_request_key IS NOT NULL;

-- Only the explicit cancellation path can assess a fee. Legacy cancellations have zero due.
CREATE FUNCTION rental_office_contract_fee(c rental_contracts) RETURNS numeric
LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN c.status='cancelled' AND c.cancellation_request_key IS NOT NULL
        THEN (c.rental_terms->>'cancellation_fee_krw')::bigint
        ELSE rental_office_fee(c.status,c.settled_amount_krw,c.starts_at,c.ends_at,c.rate_type,c.rate_amount_krw) END
$$;
ALTER TABLE rental_contracts ADD CONSTRAINT rental_cancel_terms CHECK (
    cancellation_request_key IS NULL OR COALESCE(
        status='cancelled' AND rental_terms->>'cancel_outcome' IN ('cancelled','no_show')
        AND char_length(trim(rental_terms->>'cancel_reason')) BETWEEN 1 AND 500
        AND jsonb_typeof(rental_terms->'cancellation_fee_krw')='number'
        AND (rental_terms->>'cancellation_fee_krw') ~ '^[0-9]{1,10}$'
        AND (rental_terms->>'cancellation_fee_krw')::numeric BETWEEN 0 AND 1000000000, false));

ALTER TABLE rental_fleet_work ADD COLUMN request_key uuid;
CREATE UNIQUE INDEX rental_work_request_key ON rental_fleet_work(owner_id,request_key)
    WHERE request_key IS NOT NULL;

CREATE TABLE rental_contract_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id bigint NOT NULL REFERENCES rental_contracts(id) ON DELETE CASCADE,
    event_kind text NOT NULL CHECK (event_kind IN (
        'created','updated','assigned','unassigned','extended','reviewed','review_revoked',
        'license_checked','license_revoked','activated','checkout','returned','settled','cancelled','no_show','overdue',
        'payment','refund','deposit_in','deposit_out','incident_opened','incident_closed',
        'inspection_released','return_inspection_closed')),
    occurred_at timestamptz NOT NULL,
    source_key text,
    starts_before timestamptz,
    starts_after timestamptz,
    ends_before timestamptz,
    ends_after timestamptz,
    UNIQUE(contract_id,source_key)
);
CREATE INDEX rental_contract_event_time ON rental_contract_events(contract_id,occurred_at DESC,id DESC);

-- Older workflow timestamps are JSON. Ignore malformed application data during backfill.
CREATE FUNCTION pg_temp.rental_event_time(raw text) RETURNS timestamptz LANGUAGE plpgsql AS $$
BEGIN
    IF raw IS NULL OR raw !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T' THEN RETURN NULL; END IF;
    RETURN raw::timestamptz;
EXCEPTION WHEN data_exception THEN RETURN NULL;
END $$;

INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,source_key)
SELECT c.id,x.kind,x.at,'contract:' || x.kind
FROM rental_contracts c CROSS JOIN LATERAL (VALUES
    ('created', c.created_at), ('reviewed', pg_temp.rental_event_time(c.rental_terms->>'confirmed_at')),
    ('checkout', COALESCE(pg_temp.rental_event_time(c.rental_terms->>'checkout_at'),c.pickup_signed_at)),
    ('returned', COALESCE(c.returned_at,c.return_signed_at)), ('settled', c.settled_at)
) AS x(kind,at) WHERE x.at IS NOT NULL;

INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,source_key)
SELECT c.id,l.kind,l.recorded_at,'ledger:' || l.id
FROM rental_office_ledger l JOIN rental_contracts c ON c.id=l.contract_id AND c.user_id=l.user_id;

INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,source_key)
SELECT c.id,x.kind,x.at,'work:' || w.id || ':' || x.kind
FROM rental_fleet_work w JOIN rental_contracts c ON c.id=w.contract_id AND c.user_id=w.owner_id
CROSS JOIN LATERAL (VALUES
    ('incident_opened', CASE WHEN w.kind IN ('accident','breakdown') THEN w.starts_at END),
    ('incident_closed', CASE WHEN w.kind IN ('accident','breakdown') THEN w.closed_at END),
    ('inspection_released', w.inspection_released_at),
    ('return_inspection_closed', CASE WHEN w.return_inspection THEN w.closed_at END)
) AS x(kind,at) WHERE x.at IS NOT NULL;

CREATE FUNCTION rental_capture_contract_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    kinds text[] := ARRAY[]::text[];
    k text;
    stamp timestamptz := statement_timestamp();
    old_terms jsonb;
    new_terms jsonb := COALESCE(NEW.rental_terms,'{}');
    schedule_change boolean;
    other_change boolean;
BEGIN
    IF TG_OP='INSERT' THEN
        INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,source_key)
            VALUES(NEW.id,'created',NEW.created_at,'contract:created');
        IF NEW.device_id IS NOT NULL THEN
            INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at)
                VALUES(NEW.id,'assigned',NEW.created_at);
        END IF;
        IF NEW.status<>'draft' THEN
            INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at)
                VALUES(NEW.id,CASE WHEN NEW.status='active' THEN 'activated' ELSE NEW.status END,NEW.created_at);
        END IF;
        RETURN NEW;
    END IF;

    old_terms := COALESCE(OLD.rental_terms,'{}');
    IF NEW.device_id IS DISTINCT FROM OLD.device_id THEN
        kinds := array_append(kinds, CASE WHEN NEW.device_id IS NULL THEN 'unassigned' ELSE 'assigned' END);
    END IF;
    schedule_change := (NEW.starts_at,NEW.ends_at) IS DISTINCT FROM (OLD.starts_at,OLD.ends_at);
    -- Only an actual contract edit may produce a generic "updated" entry. Privacy
    -- retention and post-handoff audit notes also touch some columns via other paths.
    IF current_setting('seriallink.rental_contract_edit', true)='on' THEN
        other_change := (NEW.renter_name,NEW.renter_phone,NEW.renter_id_last4,NEW.rate_type,NEW.rate_amount_krw,
            NEW.deposit_krw,NEW.included_km_per_day,NEW.over_km_price_krw,NEW.pickup_odometer_km,
            NEW.pickup_location,NEW.return_location,NEW.note,new_terms->>'customer_id',new_terms->>'driver_id',
            new_terms->>'driver_name',new_terms->>'requested_model',new_terms->>'channel')
            IS DISTINCT FROM
            (OLD.renter_name,OLD.renter_phone,OLD.renter_id_last4,OLD.rate_type,OLD.rate_amount_krw,
            OLD.deposit_krw,OLD.included_km_per_day,OLD.over_km_price_krw,OLD.pickup_odometer_km,
            OLD.pickup_location,OLD.return_location,OLD.note,old_terms->>'customer_id',old_terms->>'driver_id',
            old_terms->>'driver_name',old_terms->>'requested_model',old_terms->>'channel');
        IF NEW.ends_at > OLD.ends_at AND OLD.starts_at=NEW.starts_at THEN
            kinds := array_append(kinds,'extended');
        ELSIF schedule_change THEN
            other_change := true;
        END IF;
        IF other_change THEN kinds := array_append(kinds,'updated'); END IF;
    END IF;
    IF COALESCE(new_terms->>'license_checked'='true',false) <> COALESCE(old_terms->>'license_checked'='true',false) THEN
        kinds := array_append(kinds, CASE WHEN new_terms->>'license_checked'='true' THEN 'license_checked' ELSE 'license_revoked' END);
    END IF;
    IF new_terms->>'confirmed_at' IS DISTINCT FROM old_terms->>'confirmed_at' THEN
        kinds := array_append(kinds, CASE WHEN new_terms->>'confirmed_at' IS NULL THEN 'review_revoked' ELSE 'reviewed' END);
    END IF;
    IF (new_terms->>'checkout_at' IS NOT NULL AND old_terms->>'checkout_at' IS NULL)
       OR (NEW.pickup_signed_at IS NOT NULL AND OLD.pickup_signed_at IS NULL AND old_terms->>'checkout_at' IS NULL) THEN
        kinds := array_append(kinds,'checkout');
    ELSIF NEW.status='active' AND OLD.status='draft' THEN
        kinds := array_append(kinds,'activated');
    END IF;
    IF NEW.status='cancelled' AND OLD.status<>'cancelled' THEN
        UPDATE rental_handoff_tokens SET revoked_at=stamp
            WHERE contract_id=NEW.id AND user_id=NEW.user_id AND used_at IS NULL AND revoked_at IS NULL;
    END IF;
    IF NEW.status IS DISTINCT FROM OLD.status AND NEW.status IN ('cancelled','overdue','returned') THEN
        kinds := array_append(kinds,CASE WHEN NEW.status='cancelled' AND NEW.cancellation_request_key IS NOT NULL
            AND new_terms->>'cancel_outcome'='no_show' THEN 'no_show' ELSE NEW.status END);
    END IF;
    IF NEW.settled_at IS NOT NULL AND OLD.settled_at IS NULL THEN kinds := array_append(kinds,'settled'); END IF;

    FOREACH k IN ARRAY kinds LOOP
        INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,starts_before,starts_after,ends_before,ends_after)
            VALUES(NEW.id,k,stamp,CASE WHEN schedule_change AND k IN ('extended','updated') THEN OLD.starts_at END,
                CASE WHEN schedule_change AND k IN ('extended','updated') THEN NEW.starts_at END,
                CASE WHEN schedule_change AND k IN ('extended','updated') THEN OLD.ends_at END,
                CASE WHEN schedule_change AND k IN ('extended','updated') THEN NEW.ends_at END);
    END LOOP;
    RETURN NEW;
END $$;
CREATE TRIGGER rental_contract_event AFTER INSERT OR UPDATE ON rental_contracts
    FOR EACH ROW EXECUTE FUNCTION rental_capture_contract_event();

CREATE FUNCTION rental_capture_ledger_event() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,source_key)
        SELECT c.id,NEW.kind,NEW.recorded_at,'ledger:' || NEW.id FROM rental_contracts c
        WHERE c.id=NEW.contract_id AND c.user_id=NEW.user_id;
    RETURN NEW;
END $$;
CREATE TRIGGER rental_ledger_event AFTER INSERT ON rental_office_ledger
    FOR EACH ROW EXECUTE FUNCTION rental_capture_ledger_event();

CREATE FUNCTION rental_capture_work_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE k text; stamp timestamptz;
BEGIN
    IF NEW.contract_id IS NULL THEN RETURN NEW; END IF;
    IF TG_OP='INSERT' THEN
        IF NEW.kind NOT IN ('accident','breakdown') THEN RETURN NEW; END IF;
        k := 'incident_opened'; stamp := NEW.starts_at;
    ELSIF NEW.closed_at IS NOT NULL AND OLD.closed_at IS NULL THEN
        IF NEW.return_inspection THEN k := 'return_inspection_closed';
        ELSIF NEW.kind IN ('accident','breakdown') THEN k := 'incident_closed';
        ELSE RETURN NEW;
        END IF;
        stamp := NEW.closed_at;
    ELSIF NEW.inspection_released_at IS NOT NULL AND OLD.inspection_released_at IS NULL THEN
        k := 'inspection_released'; stamp := NEW.inspection_released_at;
    ELSE RETURN NEW;
    END IF;
    INSERT INTO rental_contract_events(contract_id,event_kind,occurred_at,source_key)
        SELECT c.id,k,stamp,'work:' || NEW.id || ':' || k FROM rental_contracts c
        WHERE c.id=NEW.contract_id AND c.user_id=NEW.owner_id;
    RETURN NEW;
END $$;
CREATE TRIGGER rental_work_event AFTER INSERT OR UPDATE ON rental_fleet_work
    FOR EACH ROW EXECUTE FUNCTION rental_capture_work_event();
